/* XU3 platform shim: make xfce4-panel load its plugins WITHOUT dlopen (the sandbox has none).
 *
 * xfce4-panel loads every plugin via g_module_open(<plugin.so path>) + g_module_symbol(lib,
 * "xfce_panel_module_construct"). All plugins export that SAME symbol, so they cannot all be statically
 * linked under their real names. Instead each plugin .c is compiled with a per-plugin rename
 * (-Dxfce_panel_module_construct=<name>_construct) and registered in the static table below; this shim
 * intercepts the g_module_* calls (linked via -Wl,--wrap=g_module_open,...) and resolves the construct
 * from the table by the plugin name parsed out of the .so path. The panel + plugins stay UNMODIFIED
 * upstream (constraint #5: this is a toolchain/libc-layer shim + a compile-time symbol rename).
 *
 * The static table lives in toolchain/gmodule-plugins.gen.c (generated by build-xfce4-panel.sh from the
 * set of statically-linked plugins) and provides panel_static_plugin_lookup(). */
#include <string.h>
#include <stdlib.h>
#include <unistd.h>
/* Build with -DGMODSHIM_DEBUG to trace which plugins the panel opens/resolves through the shim. */
#ifdef GMODSHIM_DEBUG
static void shimlog(const char *a, const char *b) {
  write(2, "GMODSHIM ", 9); write(2, a, strlen(a));
  if (b) { write(2, " ", 1); write(2, b, strlen(b)); }
  write(2, "\n", 1);
}
#else
static void shimlog(const char *a, const char *b) { (void) a; (void) b; }
#endif

/* Resolve a plugin entry symbol from the static table. `name` is the plugin (e.g. "separator"),
 * `symbol` is the entry point the panel asked for ("xfce_panel_module_init" for GObject/TypeModule
 * plugins, or "xfce_panel_module_construct" for simple plugins). Returns NULL if absent. Implemented in
 * the generated toolchain/gmodule-plugins.gen.c. */
void *panel_static_plugin_lookup(const char *name, const char *symbol);

/* GModule's real entry points (renamed by --wrap); we don't call them -- there's no dlopen. */
typedef int gboolean;

struct shim_handle {
  char name[128];   /* plugin name parsed from the .so path */
};

/* Parse "clock" out of ".../libclock.so" (or "libclock.la"/"clock"). */
static void plugin_name_from_path(const char *path, char *out, size_t outlen) {
  const char *base = path;
  for (const char *p = path; *p; p++)
    if (*p == '/') base = p + 1;
  if (strncmp(base, "lib", 3) == 0) base += 3;
  size_t n = 0;
  while (base[n] && base[n] != '.' && n + 1 < outlen) { out[n] = base[n]; n++; }
  out[n] = '\0';
}

void *__wrap_g_module_open(const char *file_name, int flags) {
  (void) flags;
  struct shim_handle h0;
  if (file_name == NULL) {
    return NULL; /* g_module_open(NULL)="this program"; xfce4-panel always passes a path */
  }
  plugin_name_from_path(file_name, h0.name, sizeof h0.name);
  /* Accept the open only if the plugin is statically registered (either entry style). */
  if (!panel_static_plugin_lookup(h0.name, "xfce_panel_module_init")
      && !panel_static_plugin_lookup(h0.name, "xfce_panel_module_construct"))
    return NULL;
  shimlog("open", h0.name);
  struct shim_handle *h = (struct shim_handle *) malloc(sizeof *h);
  if (!h) return NULL;
  size_t i = 0;
  for (; h0.name[i] && i + 1 < sizeof h->name; i++) h->name[i] = h0.name[i];
  h->name[i] = '\0';
  return h;
}

/* g_module_open_full(name, flags, GError**) — newer glib. Ignore the error arg. */
void *__wrap_g_module_open_full(const char *file_name, int flags, void *error) {
  (void) error;
  return __wrap_g_module_open(file_name, flags);
}

gboolean __wrap_g_module_symbol(void *handle, const char *symbol_name, void **symbol) {
  struct shim_handle *h = (struct shim_handle *) handle;
  if (!h || !symbol) return 0;
  /* GObject/TypeModule plugins export xfce_panel_module_init; simple plugins export
   * xfce_panel_module_construct. Resolve whichever the panel asks for from the static table. */
  void *fn = panel_static_plugin_lookup(h->name, symbol_name);
  if (fn) { shimlog("resolved", symbol_name); *symbol = fn; return 1; }
  *symbol = NULL;
  return 0; /* e.g. xfce_panel_module_preinit absent -> not supported for static plugins */
}

gboolean __wrap_g_module_close(void *handle) {
  free(handle);
  return 1;
}

void __wrap_g_module_make_resident(void *handle) { (void) handle; }

const char *__wrap_g_module_error(void) { return "static-plugin shim: no such plugin"; }

gboolean __wrap_g_module_supported(void) { return 1; }
