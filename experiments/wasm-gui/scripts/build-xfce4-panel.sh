#!/usr/bin/env bash
# XU3: cross-compile UNMODIFIED xfce4-panel 4.18 to wasm32-wasip1-threads. Builds libxfce4panel (the
# plugin SDK lib), common/, and the panel/ binary. Plugins are handled separately (the sandbox has no
# dlopen, so external plugins must be linked statically -- see the plugin build step). Proven Xfce
# autotools + GTK recipe (clone of build-xfwm4.sh). Constraint #5: upstream untouched; wasi/platform gaps
# in the toolchain/runtime layer.
set -uo pipefail
cd "$(dirname "$0")/.."
EXP="$(pwd)"
export SECURE_EXEC_WASM_THREADS=1
source "$EXP/toolchain/cross-env.sh"
export PATH="$EXP/toolchain/host-bin:/home/linuxbrew/.linuxbrew/bin:$PATH"
export PERL5LIB="$EXP/toolchain/host-bin/perl5:${PERL5LIB:-}"
TP="$EXP/third_party"
PV="4.18.6"
SRC="$TP/xfce4-panel"
for l in libxfce4util.a libxfce4ui-2.a libxfconf-0.a libwnck-3.a libgarcon-1.a libgarcon-gtk3-1.a libexo-2.a libhostcompat.a libdbuscreds.a; do
  [ -f "$PREFIX/lib/$l" ] || { echo "FATAL: $l missing"; exit 1; }
done

if [ ! -d "$SRC" ]; then
  curl -fsSL -o "$TP/xfce4-panel.tar.bz2" \
    "https://archive.xfce.org/src/xfce/xfce4-panel/4.18/xfce4-panel-$PV.tar.bz2" || { echo "FETCH FAILED"; exit 1; }
  ( cd "$TP" && tar xf xfce4-panel.tar.bz2 && mv "xfce4-panel-$PV" xfce4-panel )
fi

cd "$SRC"
CFG_SUB="$(ls "$TP"/libX11-threads/config.sub 2>/dev/null | head -1)"
CFG_GUESS="$(ls "$TP"/libX11-threads/config.guess 2>/dev/null | head -1)"
for d in . build-aux; do [ -d "$d" ] && cp "$CFG_SUB" "$CFG_GUESS" "$d/" 2>/dev/null || true; done
make distclean >/dev/null 2>&1
export CC="$EXP/toolchain/clang-wasi-wrap.sh"
export CFLAGS="$CFLAGS -I$PREFIX/include"
export LDFLAGS="$LDFLAGS -L$PREFIX/lib -lhostcompat"
echo "== configuring xfce4-panel =="
# --datadir=/usr/share: the panel loads data files (panel-default.xml, plugin .desktop) from the
# compile-time DATADIR, not XDG (same as xfwm4). Disable optional deps we don't have.
./configure $CROSS_CONFIGURE_ARGS \
  --datadir=/usr/share --sysconfdir=/etc \
  --enable-static --disable-shared \
  --disable-gtk-doc --disable-gtk-doc-html --disable-nls --disable-debug \
  --disable-introspection --disable-vala --disable-dbusmenu-gtk \
  > /tmp/conf-xfce4-panel.log 2>&1
RC=$?
if [ $RC -ne 0 ]; then echo "CONFIGURE FAILED; tail:"; tail -35 /tmp/conf-xfce4-panel.log; exit 1; fi

WASMSUB="wasm32-wasip1-threads"
SETJMP="$WSDK/share/wasi-sysroot/lib/$WASMSUB/libsetjmp.a"
# ★ Force-link the libxfce4ui GResource by EXTRACTING its object from the archive and linking it as a
# plain object. The register-constructor lives in libxfce4ui-resources.o inside libxfce4ui-2.a, but
# archive-pull only includes a .o that satisfies an undefined symbol; nothing references it, so it's
# dropped and the bundled dialog UI (/org/xfce/libxfce4ui/libxfce4ui-dialog-ui.ui) is never registered ->
# the first libxfce4ui dialog hits "resource does not exist" -> Gtk-ERROR abort. (--undefined/--whole-archive
# via LIBS didn't pull it -- automake dedups the repeated -l. A direct object is always linked, so its
# ctor runs.) libxfce4ui itself is UNMODIFIED -- this is pure link composition.
RESO="$EXP/toolchain/libxfce4ui-resources.o"
( cd /tmp && "$WSDK/bin/llvm-ar" x "$PREFIX/lib/libxfce4ui-2.a" libxfce4ui_2_la-libxfce4ui-resources.o 2>/dev/null \
  && mv -f libxfce4ui_2_la-libxfce4ui-resources.o "$RESO" )
echo "== building libxfce4panel + common =="
LINK0="-L$PREFIX/lib -lglibcompat $LDFLAGS -ldbuscreds -Wl,--allow-undefined -Wl,--wrap=read -Wl,--wrap=getsockopt -Wl,--wrap=writev -Wl,-z,stack-size=8388608"
make -j4 -C libxfce4panel CFLAGS="$CFLAGS" LDFLAGS="$LINK0" > /tmp/make-xfce4-panel.log 2>&1
make -j4 -C common LDFLAGS="$LINK0" >> /tmp/make-xfce4-panel.log 2>&1

# ★ STATIC PLUGINS (no dlopen in the sandbox). xfce4-panel loads every plugin via g_module_open(<.so>)
# + g_module_symbol(<entry>); the toolchain/gmodule-shim.c (linked + --wrap'd below) resolves the entry
# from a generated table instead. Each plugin's entry symbol (xfce_panel_module_init for GObject/
# TypeModule plugins, xfce_panel_module_construct for simple ones) is the SAME across plugins, so we
# rebuild each plugin .o with a per-plugin compile-time rename (-D<entry>=<name>_module_entry) and map
# it in the table. The panel + plugins stay UNMODIFIED upstream. Format: "name:entry_symbol".
STATIC_PLUGINS="${STATIC_PLUGINS:-separator:xfce_panel_module_init clock:xfce_panel_module_init tasklist:xfce_panel_module_init systray:xfce_panel_module_init applicationsmenu:xfce_panel_module_init}"
PLUGIN_OBJS=""
GENC="$EXP/toolchain/gmodule-plugins.gen.c"
{
  echo "/* GENERATED by build-xfce4-panel.sh -- static panel-plugin registry for the gmodule shim. */"
  echo "#include <string.h>"
} > "$GENC"
for spec in $STATIC_PLUGINS; do
  pname="${spec%%:*}"; entry="${spec##*:}"
  echo "== static plugin: $pname (entry $entry) =="
  rm -f "$SRC/plugins/$pname/"*"$pname".o "$SRC/plugins/$pname/"*"$pname".lo
  # Append the rename to the plugin's existing CPPFLAGS (keep the sysroot/-include wasi-compat.h etc.).
  PCPP="$(grep -m1 '^CPPFLAGS =' "$SRC/plugins/$pname/Makefile" | sed 's/^CPPFLAGS = //')"
  make -C "$SRC/plugins/$pname" CPPFLAGS="$PCPP -D$entry=${pname}_module_entry" >> /tmp/make-xfce4-panel.log 2>&1
  # Multi-file plugins (e.g. clock has 8 .c) build several lib<name>_la-*.o -- link them ALL. The -D
  # rename only affects the file defining the entry macro; it's harmless on the helpers.
  pn=0
  for PO in $(find "$SRC/plugins/$pname" -name "lib${pname}_la-*.o" 2>/dev/null); do
    dst="$EXP/toolchain/plugin-$pname-$(basename "$PO")"
    cp -f "$PO" "$dst"; PLUGIN_OBJS="$PLUGIN_OBJS $dst"; pn=$((pn+1))
  done
  echo "   ($pname: $pn object(s))"
  echo "extern void *${pname}_module_entry(void);" >> "$GENC"
done
{
  echo "void *panel_static_plugin_lookup(const char *name, const char *symbol) {"
  for spec in $STATIC_PLUGINS; do
    pname="${spec%%:*}"; entry="${spec##*:}"
    echo "  if (strcmp(name, \"$pname\") == 0 && strcmp(symbol, \"$entry\") == 0) return (void *) ${pname}_module_entry;"
  done
  echo "  return 0;"
  echo "}"
} >> "$GENC"
"$WSDK/bin/clang" --target=wasm32-wasip1-threads --sysroot="$WSDK/share/wasi-sysroot" -O2 -pthread \
  -c "$EXP/toolchain/gmodule-shim.c" -o "$EXP/toolchain/gmodule-shim.o" 2>>/tmp/make-xfce4-panel.log
"$WSDK/bin/clang" --target=wasm32-wasip1-threads --sysroot="$WSDK/share/wasi-sysroot" -O2 -pthread \
  -c "$GENC" -o "$EXP/toolchain/gmodule-plugins.gen.o" 2>>/tmp/make-xfce4-panel.log
SHIMOBJS="$EXP/toolchain/gmodule-shim.o $EXP/toolchain/gmodule-plugins.gen.o $PLUGIN_OBJS"
WRAP="-Wl,--wrap=g_module_open -Wl,--wrap=g_module_open_full -Wl,--wrap=g_module_symbol -Wl,--wrap=g_module_close -Wl,--wrap=g_module_make_resident -Wl,--wrap=g_module_error -Wl,--wrap=g_module_supported"

GTKTRANS="$RESO $SHIMOBJS -lxfce4ui-2 -lgarcon-gtk3-1 -lgarcon-1 -lexo-2 -lwnck-3 -lXinerama -latk-bridge-2.0 -latk-1.0 -lepoxy -lXi -lXrandr -lXcursor -lXcomposite -lXdamage -lXfixes -lXtst -lXft -lXrender -lXext -lX11 -lXau -lXdmcp"
LINK="$LINK0 $WRAP"
echo "== building panel binary (static plugins: $STATIC_PLUGINS) =="
# rm first: make treats an existing binary as up-to-date when only LIBS/LDFLAGS strings change.
rm -f "$SRC/panel/xfce4-panel"
make -j4 -C panel LDFLAGS="$LINK" LIBS="$GTKTRANS $SETJMP" >> /tmp/make-xfce4-panel.log 2>&1
RC=$?
echo "panel make rc=$RC"
find . -name "xfce4-panel" -type f -not -path "*.deps*" 2>/dev/null | while read f; do echo "  $(stat -c%s "$f") $f"; done
if [ $RC -ne 0 ]; then echo "(panel link incomplete; tail:)"; tail -30 /tmp/make-xfce4-panel.log; fi
echo "== libxfce4panel.a =="
find . -name "libxfce4panel-2.0.a" -o -name "libxfce4panel*.a" 2>/dev/null | head
